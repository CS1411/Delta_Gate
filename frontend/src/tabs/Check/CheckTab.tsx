import { useMemo, useState } from 'react'
import { ApiError, csvHref, downloadProof, runCheck } from '../../api'
import StructuralPanel from '../../components/StructuralPanel'
import judgeFixture from '../../fixtures/check_judge_xlookup.json'
import v2v3Fixture from '../../fixtures/check_v2_v3.json'
import { inr, signedInr } from '../../format'
import type { CheckResult, Group, Output } from '../../types'
import GroupsTable from './GroupsTable'
import HealthCoverageCard from './HealthCoverageCard'
import Waterfall from './Waterfall'

const FIXTURES: Record<string, { label: string; desc: string; data: CheckResult }> = {
  v2_v3: {
    label: 'v2 → v3 Demo',
    desc: 'Excel-Saved Golden (Full Match, Lost-Link on C4)',
    data: v2v3Fixture as CheckResult,
  },
  judge_xlookup: {
    label: 'XLOOKUP Fail-Closed Demo',
    desc: 'Partial Verification (60 XLOOKUP cells unverifiable)',
    data: judgeFixture as CheckResult,
  },
}

const fmtValue = (n: number | null) => (n === null ? 'unknown' : inr(n))
const fmtDelta = (n: number | null) => (n === null ? 'unknown' : signedInr(n))

export default function CheckTab() {
  const [baseFile, setBaseFile] = useState<File | null>(null)
  const [newFile, setNewFile] = useState<File | null>(null)
  const [result, setResult] = useState<CheckResult>(v2v3Fixture as CheckResult)
  const [isLive, setIsLive] = useState<boolean>(false)
  const [running, setRunning] = useState<boolean>(false)
  const [error, setError] = useState<string | null>(null)

  const [selectedOutputCell, setSelectedOutputCell] = useState<string>('Summary!C6')
  const [selectedGroupId, setSelectedGroupId] = useState<string | null>(null)

  // Find active watched output (defaults to Summary!C6)
  const activeOutput: Output = useMemo(() => {
    return (
      result.outputs.find((o) => o.cell === selectedOutputCell) ??
      result.outputs.find((o) => o.cell === 'Summary!C6') ??
      result.outputs[0]
    )
  }, [result, selectedOutputCell])

  const groupById = useMemo(() => {
    return new Map<string, Group>(result.groups.map((g) => [g.group_id, g]))
  }, [result.groups])

  // Currently selected group object for Cell Inspector
  const selectedGroup = useMemo(() => {
    return selectedGroupId ? groupById.get(selectedGroupId) ?? null : null
  }, [selectedGroupId, groupById])

  // Run Check (POST /api/checks with FormData)
  const handleRunCheck = async () => {
    if (!baseFile || !newFile) return
    setRunning(true)
    setError(null)
    try {
      const res = await runCheck(baseFile, newFile)
      setResult(res)
      setIsLive(true)
      const preferred = res.outputs.find((o) => o.cell === 'Summary!C6')?.cell ?? res.outputs[0]?.cell ?? ''
      setSelectedOutputCell(preferred)
      setSelectedGroupId(null)
    } catch (err) {
      setError(
        err instanceof ApiError
          ? err.message
          : "Could not reach backend API at http://localhost:8000. Showing demo fixture."
      )
    } finally {
      setRunning(false)
    }
  }

  // Load demo fixture
  const handleLoadFixture = (key: string) => {
    const f = FIXTURES[key]
    if (!f) return
    setError(null)
    setResult(f.data)
    setIsLive(false)
    const preferred = f.data.outputs.find((o) => o.cell === 'Summary!C6')?.cell ?? f.data.outputs[0]?.cell ?? ''
    setSelectedOutputCell(preferred)
    setSelectedGroupId(null)
  }

  // Prove It handler
  const handleProve = async (groupId: string) => {
    if (!isLive) {
      alert(`"Prove it" downloads the standalone proof workbook generated by the engine for live checks. (Selected: ${groupId})`)
      return
    }
    try {
      await downloadProof(result.check_id, groupId)
    } catch (err) {
      alert(err instanceof ApiError ? err.message : 'Failed to download proof workbook')
    }
  }

  // Deterministic Headline Sentence
  const causes = activeOutput.attribution.filter((a) => a.share !== 0)
  const hasUnverified = activeOutput.delta_unverified !== null && activeOutput.delta_unverified !== 0
  const observedKnown = activeOutput.delta_observed !== null

  return (
    <div className="mx-auto max-w-7xl space-y-10 px-4 py-2 sm:px-6 lg:px-8">
      {/* 01 / Interactive Folder Dropzones & Dual-Version Ingestion */}
      <section aria-label="Workbook Ingestion" className="glass-card p-6 sm:p-8">
        <div className="flex flex-wrap items-baseline justify-between gap-3 border-b border-[#D7D0C5]/70 pb-4">
          <div>
            <p className="font-mono text-xs font-bold uppercase tracking-widest text-[#7F7D74]">
              01 / COMPARATIVE DUAL INGESTION
            </p>
            <h2 className="mt-1 text-3xl font-black tracking-tight text-[#36452B]">
              Ingestion &amp; Analysis
            </h2>
          </div>

          {/* One-click Load Demo Fixture Pills */}
          <div className="flex flex-wrap items-center gap-2">
            <span className="font-mono text-xs font-bold uppercase tracking-wider text-[#7F7D74]">
              Demo Fixtures:
            </span>
            {Object.entries(FIXTURES).map(([key, f]) => (
              <button
                key={key}
                type="button"
                onClick={() => handleLoadFixture(key)}
                className="rounded-xl border border-[#D7D0C5] bg-white/80 px-3.5 py-1.5 font-mono text-xs font-bold text-[#36452B] shadow-sm transition-all hover:border-[#8A9646] hover:bg-white"
                title={f.desc}
              >
                {f.label}
              </button>
            ))}
          </div>
        </div>

        {/* Folder Cards */}
        <div className="mt-6 grid gap-6 sm:grid-cols-2">
          {/* Base Workbook Card */}
          <div className="relative">
            <div className="inline-block rounded-t-lg border-x border-t border-[#D7D0C5] bg-white/85 px-4 py-1 font-mono text-[11px] font-bold tracking-widest text-[#7F7D74]">
              BASE WORKBOOK (.xlsx)
            </div>
            <label className="group relative block cursor-pointer rounded-b-2xl rounded-tr-2xl border border-[#D7D0C5] bg-white/60 p-5 shadow-sm transition-all hover:border-[#8A9646] hover:bg-white/85">
              <div className="flex items-start justify-between">
                <div>
                  <h3 className="text-lg font-bold text-[#36452B]">
                    Baseline Version
                  </h3>
                  <p className="mt-0.5 text-xs text-[#7F7D74]">
                    Approved reference with cached values (dues_v2.xlsx)
                  </p>
                </div>
                <div className="flex h-10 w-10 items-center justify-center rounded-xl border border-[#D7D0C5]/60 bg-[#F8F7F4] text-xl">
                  📁
                </div>
              </div>
              <input
                type="file"
                accept=".xlsx,.xlsm"
                className="mt-4 block w-full text-xs text-[#36452B] file:mr-4 file:rounded-xl file:border file:border-[#D7D0C5] file:bg-[#F8F7F4] file:px-3 file:py-1.5 file:font-mono file:text-xs file:font-bold file:text-[#36452B] hover:file:bg-[#EEDADA]/40"
                onChange={(e) => setBaseFile(e.target.files?.[0] ?? null)}
              />
              {baseFile && (
                <div className="mt-2.5 flex items-center justify-between rounded-lg border border-[#8A9646]/30 bg-[#8A9646]/10 px-3 py-1 font-mono text-xs font-bold text-[#36452B]">
                  <span className="truncate">{baseFile.name}</span>
                  <span className="text-[#7F7D74]">{(baseFile.size / 1024).toFixed(1)} KB</span>
                </div>
              )}
            </label>
          </div>

          {/* New Workbook Card */}
          <div className="relative">
            <div className="inline-block rounded-t-lg border-x border-t border-[#D7D0C5] bg-white/85 px-4 py-1 font-mono text-[11px] font-bold tracking-widest text-[#7F7D74]">
              NEW WORKBOOK (.xlsx)
            </div>
            <label className="group relative block cursor-pointer rounded-b-2xl rounded-tr-2xl border border-[#D7D0C5] bg-white/60 p-5 shadow-sm transition-all hover:border-[#8A9646] hover:bg-white/85">
              <div className="flex items-start justify-between">
                <div>
                  <h3 className="text-lg font-bold text-[#36452B]">
                    Modified Candidate
                  </h3>
                  <p className="mt-0.5 text-xs text-[#7F7D74]">
                    Workbook after AI edits or user changes (dues_v3_REAL.xlsx)
                  </p>
                </div>
                <div className="flex h-10 w-10 items-center justify-center rounded-xl border border-[#D7D0C5]/60 bg-[#F8F7F4] text-xl">
                  📄
                </div>
              </div>
              <input
                type="file"
                accept=".xlsx,.xlsm"
                className="mt-4 block w-full text-xs text-[#36452B] file:mr-4 file:rounded-xl file:border file:border-[#D7D0C5] file:bg-[#F8F7F4] file:px-3 file:py-1.5 file:font-mono file:text-xs file:font-bold file:text-[#36452B] hover:file:bg-[#EEDADA]/40"
                onChange={(e) => setNewFile(e.target.files?.[0] ?? null)}
              />
              {newFile && (
                <div className="mt-2.5 flex items-center justify-between rounded-lg border border-[#8A9646]/30 bg-[#8A9646]/10 px-3 py-1 font-mono text-xs font-bold text-[#36452B]">
                  <span className="truncate">{newFile.name}</span>
                  <span className="text-[#7F7D74]">{(newFile.size / 1024).toFixed(1)} KB</span>
                </div>
              )}
            </label>
          </div>
        </div>

        {/* CTA & Status */}
        <div className="mt-6 flex flex-wrap items-center justify-between gap-4 pt-1">
          <button
            type="button"
            disabled={!baseFile || !newFile || running}
            onClick={() => void handleRunCheck()}
            className="flex h-12 items-center gap-2.5 rounded-xl bg-[#36452B] px-8 text-base font-bold text-white shadow-md transition-all hover:bg-[#36452B]/90 focus-visible:outline-4 focus-visible:outline-[#8A9646] disabled:opacity-40"
          >
            {running ? (
              <>
                <span className="h-4 w-4 animate-spin rounded-full border-2 border-white border-t-transparent" />
                Calculating Exact Shapley Coalitions…
              </>
            ) : (
              'Run Check (POST /api/checks)'
            )}
          </button>

          <div className="flex items-center gap-3">
            {!isLive ? (
              <span className="rounded-full border border-[#D7D0C5] bg-[#EEDADA]/50 px-3.5 py-1 font-mono text-xs font-bold text-[#36452B]">
                ● Displaying Engine Golden Fixture
              </span>
            ) : (
              <span className="rounded-full border border-[#8A9646] bg-[#8A9646]/15 px-3.5 py-1 font-mono text-xs font-bold text-[#36452B]">
                ✓ Live Server Check: {result.check_id}
              </span>
            )}

            {isLive ? (
              <a
                href={csvHref(result.check_id)}
                download
                className="flex items-center gap-2 rounded-xl border-2 border-[#36452B] bg-white/80 px-4 py-2 font-mono text-xs font-bold text-[#36452B] shadow-sm transition-all hover:bg-[#36452B] hover:text-white"
              >
                Export CSV
              </a>
            ) : (
              <button
                type="button"
                onClick={() => alert("CSV export is active on live backend checks.")}
                className="flex items-center gap-2 rounded-xl border border-[#D7D0C5] bg-white/60 px-4 py-2 font-mono text-xs font-bold text-[#7F7D74] shadow-sm hover:bg-white"
              >
                Export CSV (Live Only)
              </button>
            )}
          </div>
        </div>

        {error && (
          <div
            role="alert"
            className="mt-6 flex items-start gap-3 rounded-xl border border-red-300 bg-[#EEDADA]/60 p-4 text-[#36452B]"
          >
            <span className="text-xl">⚠️</span>
            <div className="text-sm font-semibold">{error}</div>
          </div>
        )}
      </section>

      {/* 02 / Watched Output Selector & KPI Cards */}
      <section aria-label="Watched Outputs Selector" className="space-y-4">
        <div className="flex items-center justify-between">
          <p className="font-mono text-xs font-bold uppercase tracking-widest text-[#7F7D74]">
            02 / WATCHED OUTPUTS &amp; KPI SUMMARY
          </p>
          <span className="font-mono text-xs text-[#7F7D74]">
            {result.outputs.length} outputs monitored by policy
          </span>
        </div>

        {/* Output Selector Pills */}
        <div role="group" aria-label="Watched outputs" className="flex flex-wrap gap-3">
          {result.outputs.map((o) => {
            const active = activeOutput.cell === o.cell
            return (
              <button
                key={o.cell}
                type="button"
                onClick={() => {
                  setSelectedOutputCell(o.cell)
                  setSelectedGroupId(null)
                }}
                className={`flex items-center gap-3 rounded-xl border-2 px-5 py-2.5 text-left transition-all ${
                  active
                    ? 'border-[#36452B] bg-[#36452B] text-white shadow-md'
                    : 'glass-card text-[#36452B] hover:border-[#8A9646]'
                }`}
              >
                <div>
                  <span className={`block text-xs font-bold ${active ? 'text-white' : 'text-[#36452B]'}`}>
                    {o.label}
                  </span>
                  <span className={`font-mono text-[11px] ${active ? 'text-[#D7D0C5]' : 'text-[#7F7D74]'}`}>
                    {o.cell}
                  </span>
                </div>
                <span className="ml-2 font-mono text-lg font-black tabular-nums">
                  {fmtDelta(o.delta_observed)}
                </span>
              </button>
            )
          })}
        </div>

        {/* KPI Cards Strip (5 Cards) */}
        <div className="grid grid-cols-2 gap-3 sm:grid-cols-5">
          <KpiCard label="Base Value" value={fmtValue(activeOutput.base)} />
          <KpiCard label="New Value" value={fmtValue(activeOutput.new)} />
          <KpiCard label="Observed Δ" value={fmtDelta(activeOutput.delta_observed)} highlight />
          <KpiCard
            label="Verified Δ"
            value={signedInr(activeOutput.delta_verified)}
            accent="moss"
          />
          <KpiCard
            label="Unverified Δ"
            value={
              activeOutput.delta_unverified === null
                ? 'unknown'
                : signedInr(activeOutput.delta_unverified)
            }
            accent={hasUnverified ? 'blossom' : 'default'}
          />
        </div>
      </section>

      {/* 03 / Deterministic Template Headline Banner */}
      <section aria-label="Executive Headline" className="glass-card p-6 sm:p-8">
        <p className="font-mono text-xs font-bold uppercase tracking-widest text-[#7F7D74]">
          DETERMINISTIC ATTRIBUTION HEADLINE · {activeOutput.label} ({activeOutput.cell})
        </p>

        <div className="mt-3">
          {!observedKnown ? (
            <div className="space-y-1">
              <h3 className="text-3xl sm:text-4xl font-black text-[#36452B]">
                Observed change: unknown
              </h3>
              <p className="text-lg font-medium text-[#7F7D74]">
                Verified change computed by engine: <b className="text-[#36452B]">{signedInr(activeOutput.delta_verified)}</b>
              </p>
            </div>
          ) : hasUnverified ? (
            <div className="space-y-3">
              <h3 className="text-3xl sm:text-4xl font-black tracking-tight tabular-nums text-[#36452B]">
                {signedInr(activeOutput.delta_observed!)} observed ={' '}
                <span className="text-[#8A9646]">{signedInr(activeOutput.delta_verified)} verified</span> +{' '}
                <span className="text-[#A44A3F]">{signedInr(activeOutput.delta_unverified!)} unverified</span>
              </h3>
              {causes.length > 0 && (
                <p className="text-base sm:text-lg text-[#7F7D74]">
                  Verified attribution split:{' '}
                  {causes.map((c, idx) => {
                    const grp = groupById.get(c.group_id)
                    const isSelected = selectedGroupId === c.group_id
                    return (
                      <button
                        key={c.group_id}
                        type="button"
                        onClick={() => setSelectedGroupId(isSelected ? null : c.group_id)}
                        className={`mx-1 inline-flex items-baseline gap-1.5 rounded-lg px-2.5 py-0.5 text-sm font-bold transition-all ${
                          isSelected
                            ? 'bg-[#36452B] text-white shadow-sm'
                            : 'bg-[#F8F7F4] text-[#36452B] border border-[#D7D0C5] hover:border-[#8A9646]'
                        }`}
                      >
                        <span className="tabular-nums">
                          {idx > 0 && c.share > 0 ? '+ ' : ''}
                          {signedInr(c.share)}
                        </span>
                        <span className="font-semibold text-xs opacity-90">
                          {grp?.label ?? c.group_id} ({grp?.type ?? 'change'})
                        </span>
                      </button>
                    )
                  })}
                </p>
              )}
            </div>
          ) : (
            <h3 className="text-3xl sm:text-4xl font-black leading-snug tabular-nums tracking-tight text-[#36452B]">
              <span>{signedInr(activeOutput.delta_observed!)}</span>
              {causes.length > 0 ? (
                <>
                  {' = '}
                  {causes.map((c, idx) => {
                    const grp = groupById.get(c.group_id)
                    const isSelected = selectedGroupId === c.group_id
                    return (
                      <button
                        key={c.group_id}
                        type="button"
                        onClick={() => setSelectedGroupId(isSelected ? null : c.group_id)}
                        className={`mx-1 inline-flex items-baseline gap-2 rounded-xl px-3 py-1 text-base sm:text-xl font-black transition-all ${
                          isSelected
                            ? 'bg-[#36452B] text-white shadow-md'
                            : 'bg-[#F8F7F4] text-[#36452B] border border-[#D7D0C5] hover:border-[#8A9646]'
                        }`}
                      >
                        <span className="tabular-nums">
                          {idx > 0 && c.share > 0 ? '+ ' : ''}
                          {signedInr(c.share)}
                        </span>
                        <span className="font-bold text-sm text-[#36452B]">
                          {grp?.label ?? c.group_id}{' '}
                          <span className="font-mono text-xs font-semibold text-[#7F7D74]">
                            ({grp?.type ?? 'change'})
                          </span>
                        </span>
                      </button>
                    )
                  })}
                </>
              ) : (
                <span className="ml-3 text-xl font-normal text-[#7F7D74]">
                  No verified attribution change
                </span>
              )}
            </h3>
          )}
        </div>
      </section>

      {/* 04 / Visual Charts Row: ECharts Waterfall (65%) + Visual Health & Coverage Card (35%) */}
      <section aria-label="Visual Charts Row" className="grid gap-6 lg:grid-cols-12">
        <div className="lg:col-span-8">
          <Waterfall
            check={result}
            outputCell={activeOutput.cell}
            selectedGroupId={selectedGroupId}
            onSelectGroup={setSelectedGroupId}
          />
        </div>
        <div className="lg:col-span-4">
          <HealthCoverageCard check={result} output={activeOutput} />
        </div>
      </section>

      {/* Visual Cell Inspector Strip (Synced with selection) */}
      {selectedGroup && (
        <section aria-label="Cell Inspector Strip" className="rounded-2xl border-2 border-[#8A9646] bg-[#8A9646]/10 p-5 shadow-sm">
          <div className="flex flex-wrap items-baseline justify-between gap-2">
            <div className="flex items-center gap-2">
              <span className="font-mono text-xs font-bold uppercase tracking-wider text-[#36452B]">
                🔍 CELL INSPECTOR:
              </span>
              <strong className="text-base text-[#36452B]">
                {selectedGroup.label} ({selectedGroup.group_id})
              </strong>
              <span className="rounded-md bg-[#36452B] px-2 py-0.5 font-mono text-[10px] font-bold uppercase text-white">
                {selectedGroup.type}
              </span>
            </div>
            <button
              type="button"
              onClick={() => setSelectedGroupId(null)}
              className="font-mono text-xs text-[#7F7D74] hover:text-[#36452B]"
            >
              ✕ Close Inspector
            </button>
          </div>

          <div className="mt-3 flex flex-wrap gap-2">
            {selectedGroup.cells.map((cell) => {
              const unv = result.unverifiable.find((u) => u.cell === cell)
              return (
                <span
                  key={cell}
                  className={`rounded-lg border px-3 py-1 font-mono text-xs font-bold ${
                    unv
                      ? 'border-red-300 bg-[#EEDADA] text-red-950'
                      : 'border-[#D7D0C5] bg-white text-[#36452B]'
                  }`}
                >
                  {cell}
                  {unv && <span className="ml-1 text-[11px] text-[#A44A3F]">({unv.reason})</span>}
                </span>
              )
            })}
          </div>
        </section>
      )}

      {/* 05 / Interactive Attribution Table */}
      <section aria-label="Change Groups Ledger">
        <GroupsTable
          groups={result.groups}
          attribution={activeOutput.attribution}
          unverifiable={result.unverifiable}
          selectedGroupId={selectedGroupId}
          onSelectGroup={setSelectedGroupId}
          onProve={handleProve}
        />
      </section>

      {/* 06 / Structural Warnings Panel & Dedicated Lost-Link Slot */}
      <section aria-label="Structural Integrity Findings">
        <div className="mb-3">
          <p className="font-mono text-xs font-bold uppercase tracking-widest text-[#7F7D74]">
            06 / STRUCTURAL INTEGRITY AUDIT
          </p>
        </div>

        {/* Mounted inside Cherry Blossom Pink (#EEDADA/40) Glass Card */}
        <div className="rounded-2xl border border-[#D7D0C5] bg-[#EEDADA]/40 p-6 sm:p-8 backdrop-blur-md shadow-sm">
          <StructuralPanel check={result} />

          {/* Dedicated container slot for Nikita's React Flow mini-graph */}
          <div
            id="lost-link-graph-slot"
            className="mt-6 rounded-xl border-2 border-dashed border-[#D7D0C5] bg-white/60 p-6 text-center"
          >
            <p className="font-mono text-xs font-bold uppercase tracking-wider text-[#7F7D74]">
              React Flow Lost-Link Graph Slot (id=&quot;lost-link-graph-slot&quot;)
            </p>
            <p className="mt-1 text-sm text-[#7F7D74]">
              {result.structural.some((s) => s.kind === 'lost_link')
                ? 'Lost link detected on watched output: Payments!C → Summary!C4 severed'
                : 'All dependency graph links intact'}
            </p>
          </div>
        </div>
      </section>

      {/* 07 / Unverifiable Cells Alert List */}
      {(result.unverifiable.length > 0 || result.verification.mismatched.length > 0) && (
        <section aria-label="Unverifiable Cells" className="glass-card border-l-8 border-[#7F7D74] p-6 sm:p-8">
          <div className="flex flex-wrap items-baseline justify-between gap-2 border-b border-[#D7D0C5]/60 pb-3">
            <div>
              <p className="font-mono text-xs font-bold uppercase tracking-widest text-[#7F7D74]">
                07 / UNVERIFIABLE CELLS (FAIL CLOSED)
              </p>
              <h3 className="mt-1 text-2xl font-black text-[#36452B]">
                Unverifiable Cells ({result.unverifiable.length})
              </h3>
            </div>
            <span className="rounded-full border border-[#D7D0C5] bg-[#EEDADA] px-3.5 py-1 text-xs font-bold uppercase tracking-wide text-[#36452B]">
              Excluded from attribution — we never guess
            </span>
          </div>

          <p className="mt-3 text-sm text-[#7F7D74]">
            Cells relying on unsupported formulas (such as XLOOKUP, dynamic arrays, or macros) cannot be verified against saved values.
          </p>

          <div className="mt-4 flex flex-wrap gap-2.5">
            {Array.from(new Set(result.unverifiable.map((u) => u.reason))).map((reason) => {
              const count = result.unverifiable.filter((u) => u.reason === reason).length
              return (
                <span
                  key={reason}
                  className="rounded-xl border border-[#D7D0C5] bg-white/80 px-4 py-1.5 font-mono text-xs font-bold text-[#36452B]"
                >
                  {reason}: <span className="tabular-nums text-[#8A9646]">{count}</span>
                </span>
              )
            })}
          </div>

          {result.verification.mismatched.length > 0 && (
            <p className="mt-4 rounded-xl border border-red-300 bg-[#EEDADA]/60 p-3 font-mono text-xs font-bold text-red-950">
              Mismatched saved values: {result.verification.mismatched.join(', ')}
            </p>
          )}

          {result.unverifiable.length > 0 && (
            <details className="mt-5">
              <summary className="cursor-pointer font-mono text-xs font-bold uppercase tracking-wider text-[#7F7D74] hover:text-[#36452B]">
                View all {result.unverifiable.length} excluded cells
              </summary>
              <ul className="mt-3 grid max-h-60 gap-2 overflow-y-auto text-xs sm:grid-cols-2 lg:grid-cols-3">
                {result.unverifiable.map((u) => (
                  <li
                    key={u.cell}
                    className="rounded-lg border border-[#D7D0C5] bg-white/80 px-3 py-2 font-mono"
                  >
                    <span className="font-bold text-[#36452B]">{u.cell}</span>{' '}
                    <span className="text-[#7F7D74]">— {u.reason}</span>
                  </li>
                ))}
              </ul>
            </details>
          )}
        </section>
      )}
    </div>
  )
}

function KpiCard({
  label,
  value,
  highlight,
  accent,
}: {
  label: string
  value: string
  highlight?: boolean
  accent?: 'moss' | 'blossom' | 'default'
}) {
  const accentClasses =
    accent === 'moss'
      ? 'border-[#8A9646]/50 bg-[#8A9646]/10 text-[#36452B]'
      : accent === 'blossom'
      ? 'border-red-300 bg-[#EEDADA] text-red-950'
      : highlight
      ? 'border-[#36452B] bg-white text-[#36452B]'
      : 'border-[#D7D0C5] bg-white/70 text-[#36452B]'

  return (
    <div className={`rounded-xl border p-4 shadow-sm ${accentClasses}`}>
      <span className="block font-mono text-[11px] font-bold uppercase tracking-wider text-[#7F7D74]">
        {label}
      </span>
      <span className="mt-1 block text-2xl font-black tabular-nums tracking-tight">
        {value}
      </span>
    </div>
  )
}
